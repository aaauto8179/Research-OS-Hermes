/**
 * Sample Financial Statements Store for Institutional Equity Research
 * Multi-period 10-year historical statements (FY15 to FY24) across P&L, Balance Sheet, and Cash Flow.
 * Anchored to real statutory filings (BSE/NSE Annual Reports, Notes to Accounts) with citation snippets.
 */

export type StatementType = 'PL' | 'BS' | 'CF';

export interface FinancialCitation {
  citationId: string;
  documentId: string;
  documentTitle: string;
  docType: 'ANNUAL_REPORT' | 'CONCALL_TRANSCRIPT' | 'INVESTOR_PRESENTATION' | 'BSE_FILING' | 'SCREENER_EXPORT';
  source: 'BSE' | 'NSE' | 'SCREENER' | 'COMPANY_WEBSITE' | 'MANUAL_UPLOAD';
  filingDate: string;
  fiscalPeriod: string; // e.g. "FY2024", "FY2023"
  pageNumber?: number;
  noteReference?: string; // e.g. "Note 28: Revenue from Operations"
  extractedSnippet: {
    textPassage?: string;
    tableSlice?: { headers: string[]; rows: (string | number)[][] };
    bbox?: { x1: number; y1: number; x2: number; y2: number };
  };
  confidence: number;
  verifiedStatus: 'VERIFIED' | 'EXTRACTED' | 'MANUAL';
  chunkId?: string;
}

export interface StatementCellData {
  value: number | null;
  unit: 'INR_CRORE' | 'PERCENT' | 'PER_SHARE' | 'COUNT';
  citation?: FinancialCitation;
}

export interface StatementLineItem {
  id: string;
  metricKey: string;
  displayName: string;
  category: 'REVENUE' | 'OPERATING_EXPENSE' | 'OPERATING_PROFIT' | 'TAX' | 'NET_PROFIT' | 'ASSET' | 'LIABILITY' | 'CASH_FLOW' | 'RATIO';
  isSummary: boolean;
  indentationLevel: number;
  periods: Record<string, StatementCellData>;
  subItems?: StatementLineItem[];
}

export interface BusinessSegment {
  name: string;
  description: string;
  revenueFY24: number;
  ebitdaFY24: number;
  marginPct: number;
}

export interface CompanyStatementData {
  symbol: string;
  companyName: string;
  industry: string;
  currency: string;
  unit: string;
  fiscalYears: string[];
  statements: {
    PL: StatementLineItem[];
    BS: StatementLineItem[];
    CF: StatementLineItem[];
  };
  segments?: BusinessSegment[];
}

export const FISCAL_YEARS = [
  'FY15', 'FY16', 'FY17', 'FY18', 'FY19', 'FY20', 'FY21', 'FY22', 'FY23', 'FY24'
];

function cell(val: number | null, unit: StatementCellData['unit'] = 'INR_CRORE', citation?: FinancialCitation): StatementCellData {
  return { value: val, unit, citation };
}

